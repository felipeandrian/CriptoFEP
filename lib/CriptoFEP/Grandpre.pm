=head2 grandpre_encrypt
 
 Encrypts plaintext using the Grandpré cipher.
 
 B<Parameters:>
   - $plaintext (string): The plaintext to be encrypted.
   - $keys (array ref): An array ref containing [ $alphabet_key, $position_key ].
 
 B<Returns:>
   - (string): The resulting ciphertext.
 
=cut
sub grandpre_encrypt {
    my ($plaintext, $keys) = @_;
    my ($alphabet_key, $position_key) = @$keys;
    
    # Normalize plaintext, combining I/J.
    my $norm_plain = normalize_text($plaintext);
    $norm_plain =~ s/J/I/g;
    
    # Pre-generate the entire progressive keystream.
    my ($keystream, $key_alpha, $key_pos) = _get_keystream_and_alphabet($alphabet_key, $position_key, length($norm_plain));
    
    my $ciphertext = "";
    my @plain_chars = split //, $norm_plain;
    my @key_chars = split //, $keystream;
    
    # Perform the Vigenere addition using the mixed alphabet.
    for (my $i = 0; $i < @plain_chars; $i++) {
        my $p_idx = $key_pos->{ $plain_chars[$i] };
        my $k_idx = $key_pos->{ $key_chars[$i] };
        
        # Handle invalid characters (this should be rare after normalization).
        if (not defined $p_idx or not defined $k_idx) {
            $ciphertext .= $plain_chars[$i]; 
            next;
        }
        
        # Apply the Vigenere formula: (P + K) mod 25
        my $c_idx = ($p_idx + $k_idx) % 25;
        $ciphertext .= $key_alpha->[$c_idx];
    }
    return $ciphertext;
}

=head2 grandpre_decrypt
 
 Decrypts ciphertext using the Grandpré cipher.
 
 B<Parameters:>
   - $ciphertext (string): The ciphertext to be decrypted.
   - $keys (array ref): An array ref containing [ $alphabet_key, $position_key ].
 
 B<Returns:>
   - (string): The original plaintext.
 
=cut
sub grandpre_decrypt {
    my ($ciphertext, $keys) = @_;
    my ($alphabet_key, $position_key) = @$keys;
    
    my $norm_cipher = normalize_text($ciphertext);
    $norm_cipher =~ s/J/I/g;
    
    # Re-generate the *exact same* progressive keystream that was used to encrypt.
    my ($keystream, $key_alpha, $key_pos) = _get_keystream_and_alphabet($alphabet_key, $position_key, length($norm_cipher));

    my $plaintext = "";
    my @cipher_chars = split //, $norm_cipher;
    my @key_chars = split //, $keystream;

    for (my $i = 0; $i < @cipher_chars; $i++) {
        my $c_idx = $key_pos->{ $cipher_chars[$i] };
        my $k_idx = $key_pos->{ $key_chars[$i] };
        
        if (not defined $c_idx or not defined $k_idx) {
            $plaintext .= $cipher_chars[$i];
            next;
        }
        
        # Apply the Vigenere inverse formula: (C - K) mod 25
        my $p_idx = ($c_idx - $k_idx + 25) % 25;
        $plaintext .= $key_alpha->[$p_idx];
    }
    return $plaintext;
}

