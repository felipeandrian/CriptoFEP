=head2 _generate_key_data
 
 Internal helper function to build the 25-letter (I/J combined) mixed alphabet
 and its corresponding lookup maps based on the alphabet key.
 
 B<Parameters:>
   - $key (string): The secret key (e.g., "SECRET") used to shuffle the alphabet.
 
 B<Returns:>
   - A list containing two references:
     1. (array ref): The 25-letter shuffled alphabet.
     2. (hash ref): A map of {Letter => Position} (e.g., 'S' => 0, 'E' => 1...).
 
=cut
sub _generate_key_data {
    my ($key) = @_;
    
    # Normalize the key and combine 'J' with 'I'.
    my $norm_key = normalize_text($key);
    $norm_key =~ s/J/I/g; 
    
    # Define the 25-letter base alphabet.
    my @alphabet_25_base = ('A'..'H', 'I', 'K'..'Z'); # The base alphabet without 'J'
    my %seen;
    
    # 1. Start the new alphabet with the unique letters from the key.
    my @shuffled_alphabet = grep { !$seen{$_}++ } split //, $norm_key;
    
    # 2. Add the remaining letters from the base alphabet.
    foreach my $char (@alphabet_25_base) {
        push @shuffled_alphabet, $char unless $seen{$char};
    }
    
    # Ensure the alphabet is exactly 25 letters long.
    @shuffled_alphabet = @shuffled_alphabet[0..24];

    # Create the reverse map (Letter -> Position).
    my %pos_map; # Map: Letter -> Position (0-24)
    @pos_map{@shuffled_alphabet} = (0..24);
    
    # Return both the list (for index-to-letter) and the map (for letter-to-index).
    return (\@shuffled_alphabet, \%pos_map);
}

=head2 _get_keystream_and_alphabet
 
 Internal helper function that generates the full-length progressive keystream.
 This is the "odometer" logic of the cipher.
 
 B<Parameters:>
   - $alphabet_key (string): The key for generating the mixed alphabet.
   - $position_key (string): The initial state of the evolving key.
   - $text_len (integer): The length of the text to be encrypted/decrypted.
 
 B<Returns:>
   - A list containing three references:
     1. (string): The fully generated, text-length progressive keystream.
     2. (array ref): The 25-letter shuffled alphabet.
     3. (hash ref): The {Letter => Position} map.
 
=cut
sub _get_keystream_and_alphabet {
    my ($alphabet_key, $position_key, $text_len) = @_;

    # Generate the mixed alphabet and its position map.
    my ($key_alpha, $key_pos) = _generate_key_data($alphabet_key);
    
    # Normalize the position key (e.g., "KEY"), ensuring it also combines I/J.
    my $norm_pos_key = normalize_text($position_key);
    $norm_pos_key =~ s/J/I/g; 
    
    # We will modify this array in-place as the key "evolves".
    my @pos_key_chars = split //, $norm_pos_key;
    my $pos_key_len = scalar @pos_key_chars;
    
    my $keystream = "";
    
    # Loop for the entire length of the message.
    for (my $i = 0; $i < $text_len; $i++) {
        # Find the current key letter to use (e.g., K, E, Y, K, E, Y...)
        my $key_char_index = $i % $pos_key_len;
        my $current_key_char = $pos_key_chars[$key_char_index];
        
        # Security check: Ensure the key letter exists in our alphabet.
        unless (exists $key_pos->{$current_key_char}) {
             die "Error: Position key character '$current_key_char' is invalid " .
                 "(not in the mixed alphabet generated by '$alphabet_key').\n";
        }
        
        # 1. Add the current key character to the final keystream.
        $keystream .= $current_key_char;
        
        # 2. Find the *next* letter in the mixed alphabet (the "odometer" tick).
        my $char_pos = $key_pos->{$current_key_char};
        my $next_pos = ($char_pos + 1) % 25;
        my $next_char = $key_alpha->[$next_pos];
        
        # 3. Update the position key in memory for the *next* time this index is used.
        $pos_key_chars[$key_char_index] = $next_char;
    }
    
    # Return the generated keystream and the alphabet data.
    return ($keystream, $key_alpha, $key_pos);
}


