    return qq(CIPHER: Grandpré Cipher

DESCRIPTION:
    A polyalphabetic substitution cipher, similar to Vigenere, but which uses
    a "progressive key" (or "odometer key") to defeat standard frequency 
    analysis. The key itself evolves during the encryption process,
    making it significantly stronger than a standard Vigenere.

MECHANISM (ENCRYPTION):
    The cipher requires two keys:
    1. Alphabet Key (e.g., -k SECRET): Used to create a 25-letter 
